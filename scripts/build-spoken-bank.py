#!/usr/bin/env python3
"""Authoring-only French speech bank. Runtime uses embedded PCM, never network TTS.
Requires local espeak and ffmpeg, not dependencies of the game.
"""
import subprocess, tempfile, pathlib, wave, json, base64, hashlib
import numpy as np
ROOT=pathlib.Path(__file__).resolve().parents[1]
texts=dict(zip('ABCDEFGHIJKLMNOPQRSTUVWXYZ', ['a','bé','cé','dé','e','èf','gé','ache','i','ji','ka','èl','èm','èn','o','pé','ku','èr','ès','té','u','vé','double vé','iks','i grec','zèd']))
texts.update(dict(zip('0123456789',['zéro','un','deux','trois','quatre','cinq','six','sept','huit','neuf'])))
texts.update({'-':'tiret','_':'tiret bas',' ':'espace','future':'La lampe du poste va s’éteindre.'})
bank={}
with tempfile.TemporaryDirectory() as temp:
 for key,text in texts.items():
  wav=pathlib.Path(temp)/'voice.wav';raw=pathlib.Path(temp)/'voice.pcm'
  subprocess.run(['espeak','-v','fr','-s','160','-p','32','-a','80','-w',str(wav),'--',text],check=True,stdout=subprocess.DEVNULL,stderr=subprocess.DEVNULL)
  subprocess.run(['ffmpeg','-v','error','-y','-i',str(wav),'-ar','8000','-ac','1','-f','s16le',str(raw)],check=True)
  values=np.frombuffer(raw.read_bytes(),dtype='<i2').astype(float)/32768
  indices=np.flatnonzero(abs(values)>.008)
  if not len(indices):raise ValueError(key)
  values=values[max(0,indices[0]-100):min(len(values),indices[-1]+160)]
  values*=.72/max(abs(values))
  # Mu-law companding, unsigned 8-bit; decoder is explicit in spoken-pcm.ts.
  mu=np.sign(values)*np.log1p(255*abs(values))/np.log(256)
  encoded=np.clip(np.rint((mu+1)*127.5),0,255).astype(np.uint8).tobytes()
  bank[key]={'text':text,'data':base64.b64encode(encoded).decode(),'seconds':len(encoded)/8000}
body='// Generated by scripts/build-spoken-bank.py. Original synthetic French phrases/letters.\nexport const SPOKEN_RATE=8000;\nexport const SPOKEN_BANK:Record<string,{text:string;data:string;seconds:number}>='+json.dumps(bank,ensure_ascii=False,separators=(',',':'))+';\n'
(ROOT/'src/game/spoken-bank.ts').write_text(body)
timing='// Same timings as the embedded offline bank, without importing the audio payload in scene tests.\nexport const SPOKEN_DURATIONS:Record<string,number>='+json.dumps({k:v['seconds'] for k,v in bank.items()},ensure_ascii=False,separators=(',',':'))+';\nexport const FUTURE_SENTENCE='+json.dumps(bank['future']['text'],ensure_ascii=False)+';\n'
(ROOT/'src/game/spoken-timing.ts').write_text(timing)
manifest={'engine':subprocess.check_output(['espeak','--version'],text=True).strip(),'sample_rate':8000,'encoding':'unsigned 8-bit mu-law, formula in decoder','purpose':'Original offline synthetic phrases and spelling; no recorded person or external service','samples':{k:{'text':v['text'],'seconds':v['seconds'],'sha256':hashlib.sha256(base64.b64decode(v['data'])).hexdigest()} for k,v in bank.items()}}
(ROOT/'docs/spoken-bank-manifest.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n')
print(json.dumps({'bytes':len(body.encode()),'seconds':sum(v['seconds'] for v in bank.values()),'tokens':len(bank)}))
